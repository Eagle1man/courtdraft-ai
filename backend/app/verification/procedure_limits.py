"""Пороги видов производства (ч. 1 ст. 121, п. 1 ч. 1 ст. 122,
п. 1 ч. 1 ст. 232.2 ГПК РФ).

Проверка ничего не решает за судью и ничего не блокирует: она только
показывает, что по цене иска дело могло пойти другим путём, и напоминает
проверить это. Как и в проверке подсудности, признак берётся из
материалов — порог приказного производства поднимается в замечание
только если о судебном приказе в материалах действительно сказано.

Пороги сверены с первоисточником 2026-10-26: упрощённое производство —
250 000 руб. (повышено с 100 000), приказное — 500 000 руб.
"""

from __future__ import annotations

import re
from dataclasses import dataclass

#: Приказное производство: денежные требования в пределах 500 000 руб.
#: (ч. 1 ст. 121, п. 1 ч. 1 ст. 122 ГПК РФ).
ORDER_LIMIT: float = 500_000.0

#: Упрощённое производство: цена иска до 250 000 руб.
#: (п. 1 ч. 1 ст. 232.2 ГПК РФ).
SIMPLIFIED_LIMIT: float = 250_000.0


def _rub(value: float) -> str:
    """Сумма в тексте замечания: 500 000, а не 500000."""
    return f"{value:,.0f}".replace(",", " ")

#: Судебный приказ в материалах дела: выдан, отменён, отказано в выдаче.
_ORDER_RE = re.compile(
    r"судебн\w*\s+приказ|о\s+выдаче\s+приказа|в\s+выдаче\s+приказа\s+отказано",
    re.IGNORECASE,
)

#: Дело уже идёт в упрощённом порядке — напоминание не нужно.
_SIMPLIFIED_RE = re.compile(
    r"упрощ\w*\s+(?:производ|поряд)|гл\.?\s*21\.1|ст(?:атьи|\.|ьей)?\s*232\.2",
    re.IGNORECASE,
)

#: Слышно судебное заседание — упрощённое производство уже невозможно,
#: и напоминание о нём было бы шумом.
_HEARING_RE = re.compile(
    r"заседан|судебное\s+слухание|в\s+совещательн\w*\s+комнат",
    re.IGNORECASE,
)


@dataclass(frozen=True)
class ProcedureFinding:
    """Напоминание о виде производства для судьи."""

    kind: str  # «order» / «order_over» — приказное, «simplified» — упрощённое
    reason: str


def mentions_simplified(texts: list[str]) -> bool:
    """Сказано ли в материалах, что дело идёт в упрощённом порядке.

    Отличается от напоминания о пороге: там проверяется, что дело МОГЛО
    пойти по упрощённой схеме, здесь — что оно действительно идёт
    по ней, и сроки обжалования должны быть другие (ст. 232.4 ГПК РФ).
    """
    return bool(_SIMPLIFIED_RE.search("\n".join(texts)))


def check_procedure_limits(
    texts: list[str], claim_total: float
) -> list[ProcedureFinding]:
    """Напомнить про пороги приказного и упрощённого производства.

    Приказное поднимается только при явном упоминании приказа в
    материалах: само по себе «цена иска меньше 500 000» не говорит
    о том, что приказ вообще в деле встречался. Упрощённое — по цене
    иска, но только когда в материалах ни упрощённого порядка, ни
    следа заседания.
    """
    if claim_total <= 0:
        return []
    joined = "\n".join(texts)
    findings: list[ProcedureFinding] = []

    if _ORDER_RE.search(joined):
        if claim_total > ORDER_LIMIT:
            findings.append(
                ProcedureFinding(
                    kind="order_over",
                    reason=(
                        f"в материалах упомянут судебный приказ, а цена иска "
                        f"{_rub(claim_total)} руб. превышает порог приказного "
                        f"производства {_rub(ORDER_LIMIT)} руб. "
                        "(ч. 1 ст. 121 ГПК РФ)"
                    ),
                )
            )
        else:
            findings.append(
                ProcedureFinding(
                    kind="order",
                    reason=(
                        f"цена иска {_rub(claim_total)} руб. в пределах порога "
                        f"приказного производства {_rub(ORDER_LIMIT)} руб. "
                        "(ч. 1 ст. 121, п. 1 ч. 1 ст. 122 ГПК РФ): проверить, "
                        "не выносился ли приказ по тем же требованиям — "
                        "повторное обращение останавливается"
                    ),
                )
            )

    if (
        claim_total <= SIMPLIFIED_LIMIT
        and not _SIMPLIFIED_RE.search(joined)
        and not _HEARING_RE.search(joined)
    ):
        findings.append(
            ProcedureFinding(
                kind="simplified",
                reason=(
                    f"цена иска {_rub(claim_total)} руб. в пределах "
                    f"{_rub(SIMPLIFIED_LIMIT)} руб., признаков заседания в "
                    "материалах нет: дело могло рассматриваться в упрощённом "
                    "порядке (п. 1 ч. 1 ст. 232.2 ГПК РФ), апелляция — "
                    "15 дней (ст. 232.4 ГПК РФ)"
                ),
            )
        )

    return findings
