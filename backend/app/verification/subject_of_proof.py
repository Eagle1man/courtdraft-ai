"""Предмет доказывания по виду договора (п. 5.4, 11.3 разбора).

Для каждой категории дел положен перечень обстоятельств, подлежащих
установлению. Система показывает судье таблицу: какое обстоятельство
каким документом подтверждено, а какое — ничем. Это не вывод о правоте
сторон, а карта доказательств: решение остаётся за судьёй.

Перечень зависит от вида договора: по предмету доказывания поставки
(10 обстоятельств) и аренда (6) не совпадают — поставка спорит о
передаче товара и цене, аренда — о приёме-передаче имущества и плате
за просрочку его возврата. Пакет DeepSeek v1.1 даёт четыре матрицы
(``proof_matrix``), они перенесены сюда со своими маркерами.

Вид договора определяется по маркерам в текстах материалов дела —
это эвристика, а не квалификация спора: неверный вид меняет перечень
строк таблицы, но не превращается в вывод о правах сторон. Если
ни один маркер не нашёлся, берётся общий перечень по взысканию
задолженности (``DEBT_FACTS``).

Обстоятельство считается освещённым, когда хотя бы один документ дела
содержит маркер категории; этим документом и ссылается таблица. Ни
одного — обстоятельство остаётся неподтверждённым, и это должно быть
видно в блоке «Не хватает данных», а не спрятано за общими словами
о «совокупности доказательств».
"""

from __future__ import annotations

