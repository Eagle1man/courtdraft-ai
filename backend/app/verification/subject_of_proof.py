#: Общий вид — когда ни один маркер не нашёлся.
DEFAULT_KIND = "долг"


def contract_kind(items: list[EvidenceItem]) -> str:
    """Определить вид договора по маркерам в текстах материалов дела.

    Возвращает ключ ``MATRICES``. Считаются вхождения маркеров с весом;
    при равенстве побеждает тот вид, что перечислен первым. Ничего не
    найдено — общий перечень ``DEBT_FACTS``: молчание по неизвестному
    виду честнее, чем чужая таблица.
    """
    texts = [item.text.lower() for item in items]
    best_kind = DEFAULT_KIND
    best_score = 0
    for kind, markers in _MARKERS.items():
        score = 0
        for marker, weight in markers:
            for text in texts:
                score += weight * min(text.count(marker), 2)
        if score > best_score:
            best_kind = kind
            best_score = score
    return best_kind


def subject_of_proof(
    items: list[EvidenceItem], kind: str | None = None
) -> list[ProofFact]:
    """Таблица «обстоятельство — доказательства» по материалам дела.

    ``kind`` — вид договора (ключ ``MATRICES``); если не задан, он
    определяется по маркерам материалов. Документ считается упоминанием
    обстоятельства, когда маркер нашёлся в тексте его фрагмента. По
    одному документу в списке источников не повторяемся.
    """
    matrix = MATRICES.get(kind or contract_kind(items), DEBT_FACTS)
    facts: list[ProofFact] = []
    for circumstance, markers in matrix:
        docs: list[str] = []
        for item in items:
            text = item.text.lower()
            if any(marker in text for marker in markers) and (
                item.source_document not in docs
            ):
                docs.append(item.source_document)
        facts.append(
            ProofFact(
                circumstance=circumstance,
                docs=tuple(docs),
                covered=bool(docs),
            )
        )
    return facts


def proof_gaps(items: list[EvidenceItem], kind: str | None = None) -> list[str]:
    """Неподтверждённые обстоятельства — строки для блока «Не хватает данных».

    Пустой список, когда подтверждено всё: пробел в блоке — это
    требование к судье что-то додумать, и без нужды его показывать
    нельзя.
    """
    return [
        f"обстоятельство «{fact.circumstance}» не подтверждено ни одним "
        "документом дела"
        for fact in subject_of_proof(items, kind)
        if not fact.covered
    ]
