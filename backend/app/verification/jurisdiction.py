"""Проверка родовой подсудности (п. 4 и п. 5 ч. 1 ст. 23 ГПК РФ).

Имущественный спор при цене иска до 50 000 руб. включительно
рассматривает мировой судья, свыше — районный суд. Споры о защите прав
потребителей подсудны мировому судье до 100 000 руб. включительно —
это отдельный пункт с отдельным порогом, и подменять им общий нельзя:
раньше здесь стоял потребительский порог как общий, и дело с ценой
иска 89 000 руб. у мирового судьи проходило молча, хотя по п. 4 оно
подсудно районному суду.

Проверка не решает за судью: она сверяет цену иска с тем судом, который
назван в материалах, и расхождение показывает судье. Суд из материалов
не определяется — это признак, а не выдумка.

Подведомственность «арбитраж или общая юрисдикция» (ст. 27, 28 АПК РФ,
ч. 2.1 ст. 33 ГПК РФ) здесь не решается: она требует установления рода
деятельности сторон, который по текстам материалов уверенно не
определяется. Родовая подсудность — закрытое правило с числом, его
можно проверять честно.
"""

from __future__ import annotations

import re
from dataclasses import dataclass

#: Порог родовой подсудности: п. 4 ч. 1 ст. 23 ГПК РФ — иные
#: имущественные споры при цене иска до 50 000 руб. включительно
#: рассматривает мировой судья.
WORLD_LIMIT: float = 50_000.0

#: Порог по спорам о защите прав потребителей: п. 5 ч. 1 ст. 23
#: ГПК РФ — до 100 000 руб. включительно. Пункт отдельный и порог
#: свой, применять его ко всем имущественным спорам нельзя.
CONSUMER_LIMIT: float = 100_000.0

#: Признаки спора о защите прав потребителей в материалах дела.
#: Потребительский порог включается только по явному признаку:
#: молчаливое предположение вернуло бы старую ошибку в другую сторону.
_CONSUMER_RE = re.compile(
    r"защит\w*\s+прав\w*\s+потребител|права\s+потребител",
    re.IGNORECASE,
)

_WORLD_RE = re.compile(r"миров\w*\s+суд\w*", re.IGNORECASE)
_DISTRICT_RE = re.compile(r"районн\w*\s+суд\w*", re.IGNORECASE)


@dataclass(frozen=True)
class JurisdictionFinding:
    """Расхождение между ценой иска и судом в материалах."""

    expected: str  # «мировой судья» | «районный суд»
    found: str  # что написано в материалах
    reason: str  # готовый текст замечания


def expected_tier(price: float, consumer: bool = False) -> str:
    """Какой суд должен рассматривать спор по цене иска.

    Потребительский порог (100 000 руб.) применяется только когда спор
    о защите прав потребителей виден по материалам, иначе — общий
    (50 000 руб., п. 4 ч. 1 ст. 23 ГПК РФ).
    """
    limit = CONSUMER_LIMIT if consumer else WORLD_LIMIT
    if 0 < price <= limit:
        return "мировой судья"
    return "районный суд"


def _rub(value: float) -> str:
    """Сумма в тексте замечания: 89 122, а не 89122."""
    return f"{value:,.0f}".replace(",", " ")


def court_tier(text: str) -> str | None:
    """Инстанция, названная в тексте: мировой судья, районный суд, нет."""
    return _court_tier_in(text)


def _court_tier_in(text: str) -> str | None:
    if _WORLD_RE.search(text):
        return "мировой судья"
    if _DISTRICT_RE.search(text):
        return "районный суд"
    return None


def check_jurisdiction(
    court_texts: list[str], claim_total: float
) -> list[JurisdictionFinding]:
    """Сверить цену иска с судом, названным в материалах.

    Тексты материалов передаются списком: суд ищется по всем
    документам дела, а не по первому попавшемуся. Материалы не называют
    суд — проверка молчит: отсутствие признака не превращается в
    замечание.

    Из тех же текстов определяется, не потребительский ли спор: если
    да, порог 100 000 руб. (п. 5 ч. 1 ст. 23 ГПК РФ), если нет —
    общий 50 000 руб. (п. 4 ч. 1 ст. 23 ГПК РФ).
    """
    if claim_total <= 0:
        return []
    consumer = any(_CONSUMER_RE.search(text) for text in court_texts)
    expected = expected_tier(claim_total, consumer)
    point = "п. 5" if consumer else "п. 4"
    kind = (
        "спор о защите прав потребителей подсуден"
        if consumer
        else "родовая подсудность —"
    )
    for text in court_texts:
        found = _court_tier_in(text)
        if found is None:
            continue
        if found != expected:
            return [
                JurisdictionFinding(
                    expected=expected,
                    found=found,
                    reason=(
                        f"при цене иска {_rub(claim_total)} руб. {kind} "
                        f"{expected} ({point} ч. 1 ст. 23 ГПК РФ), "
                        f"а в материалах дела указан {found}: проверить, "
                        "куда передано дело"
                    ),
                )
            ]
        return []
    return []
