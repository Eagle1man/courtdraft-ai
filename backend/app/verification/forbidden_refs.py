"""Ссылки, которых в гражданском решении быть не должно.

Разбор пакета DeepSeek v1.1 (2026-10-26), блок ``forbidden_refs``.
Правила описывают ошибки, которые система допускала раньше и которые
проверка не ловила: каждая ссылка в проекте либо существует в кодексе
(и потому проходит проверку наличия статьи), либо взята из материалов
дела (и потому проходит проверку подтверждения). Оставалась дыра —
ссылка законная, но не про то.

Здесь только то, что видно в тексте акта. Вид договора берётся из
материалов: ст. 779 ГК РФ запрещена в споре о поставке, но в споре об
услугах она законна, и проверка обязана это различать.
"""

from __future__ import annotations

import re
from dataclasses import dataclass

#: «ст. 131», «ст.132», «статьи 131», «статье 132» — форма искового
#: заявления и приложения к нему (пп. 3 пакета: основанием иска не
#: служат, в мотивировке решения не указываются).
_ART_131_132 = re.compile(r"\bст[а-яё]*\.?\s*13[12]\b", re.IGNORECASE)

#: «ст. 310» — запрет одностороннего отказа от исполнения. Сама по себе
#: ссылка законна; запрещена как основание взыскания неустойки.
_ART_310 = re.compile(r"\bст[а-яё]*\.?\s*310\b", re.IGNORECASE)

#: «ст. 779», «ст. 781» — возмездное оказание услуг.
_ART_SERVICES = re.compile(r"\bст[а-яё]*\.?\s*(?:779|781)\b", re.IGNORECASE)

#: «ст. 395» — проценты за пользование чужими денежными средствами.
_ART_395 = re.compile(r"\bст[а-яё]*\.?\s*395\b", re.IGNORECASE)

#: Неустойка или пеня — та же функция, что и в проверке ст. 310.
_PENALTY = re.compile(r"неустойк|пен[еиёя]", re.IGNORECASE)

#: Суд что-то присуждает, а не просто рассуждает о нормах.
_AWARD = re.compile(r"взыскать|удовлетворить|подлежит взысканию", re.IGNORECASE)

#: Проценты по ст. 395 прямо не взыскиваются — тогда пары нет, спор
#: разрешён в одном направлении.
_NO_395 = re.compile(r"не\s+взыска|не\s+подлеж|отказать", re.IGNORECASE)

#: Уголовный, уголовно-процессуальный и административный кодексы в
#: гражданском акте. Ловится и прямая ссылка («ст. 15 УПК РФ»), и
#: название кодекса («Уголовно-процессуальный кодекс РФ»).
_FOREIGN_CODE = re.compile(
    r"\b(?:УК|УПК|КоАП)\s+РФ"
    r"|\bУголовно[-\s]процессуальн\w*\s+кодекс"
    r"|\bУголовн\w*\s+кодекс"
    r"|\bКодекс\w*\s+об\s+административн\w*\s+правонарушен",
    re.IGNORECASE,
)

#: Вводная формула резолютивной части и то, что идёт до «суд решил».
#: Окно, а не «до точки»: внутри формулы стоит «ст.» — и точка после
#: сокращения обрывала бы поиск ровно посередине ссылки.
_PREAMBLE_RE = re.compile(
    r"Руководствуясь.{0,160}?суд\s+решил", re.IGNORECASE | re.DOTALL
)
_ART_198 = re.compile(r"\bст[а-яё]*\.?\s*198\b", re.IGNORECASE)
_ART_194 = re.compile(r"\bст[а-яё]*\.?\s*194\b", re.IGNORECASE)

#: Граница фразы для поиска пар «ст. 310 + неустойка»: проверка парная,
#: и разделить здесь фразы нужно честно — точка после «ст.» границы
#: не делает, иначе «неустойку по ст. 310 ГК РФ» распадается на два
#: куска, в каждом из которых половины признака не хватает.
_SENTENCE_SPLIT = re.compile(r"(?<=[.!?])\s+")
_ABBREV_END = re.compile(r"\b(?:ст|ч|п|пп|абз|подп|гр)\.$", re.IGNORECASE)


@dataclass(frozen=True)
class ForbiddenFinding:
    """Ссылка, которая в гражданском решении неуместна."""

    kind: str
    reason: str
    #: Уровень из разбора: «foreign_code» — R13 (критично), «form_only» —
    #: R14 (существенно), «penalty_395» — R20 (существенно); остальные
    #: по тяжеце ошибки в самом акте.
    severity: str  # "CRITICAL" | "HIGH" | "MEDIUM"


def _sentences(text: str) -> list[str]:
    parts = [part.strip() for part in _SENTENCE_SPLIT.split(text) if part.strip()]
    merged: list[str] = []
    for part in parts:
        if merged and _ABBREV_END.search(merged[-1]):
            # Точка после «ст.» — не конец фразы: склеиваем обратно.
            merged[-1] = f"{merged[-1]} {part}"
            continue
        merged.append(part)
    return merged


def check_forbidden_refs(
    text: str, *, supply: bool = False
) -> list[ForbiddenFinding]:
    """Найти в тексте акта ссылки, которых там быть не должно.

    ``supply`` — спор идёт по договору поставки (признак из материалов
    дела). Без него проверка на ст. 779 и 781 ГК РФ молчит: в споре об
    оказании услуг эти статьи законны.

    Отдельно ловится пара «неустойка + проценты по ст. 395 ГК РФ»
    (R20): за один и тот же период это двойная ответственность, и
    проект обязан взыскивать что-то одно.
    """
    findings: list[ForbiddenFinding] = []

    for match in _FOREIGN_CODE.finditer(text):
        findings.append(
            ForbiddenFinding(
                kind="foreign_code",
                reason=(
                    f"в проект решения попала ссылка ({match.group().strip()}) "
                    "на кодекс, который к гражданскому делу не применяется: "
                    "УК РФ, УПК РФ и КоАП РФ спор о долге не регулируют, "
                    "основание — нормы ГК РФ и договора"
                ),
                severity="CRITICAL",
            )
        )

    if _ART_131_132.search(text):
        findings.append(
            ForbiddenFinding(
                kind="form_only",
                reason=(
                    "ст. 131 и 132 ГПК РФ описывают форму искового заявления "
                    "и приложения к нему: они не служат основанием иска и в "
                    "мотивировке решения не указываются"
                ),
                severity="MEDIUM",
            )
        )

    for sentence in _sentences(text):
        if _ART_310.search(sentence) and _PENALTY.search(sentence):
            findings.append(
                ForbiddenFinding(
                    kind="penalty_310",
                    reason=(
                        "ст. 310 ГК РФ запрещает односторонний отказ от "
                        "исполнения, к взысканию неустойки основание — "
                        "ст. 330 ГК РФ"
                    ),
                    severity="HIGH",
                )
            )
            break

    if supply and _ART_SERVICES.search(text):
        findings.append(
            ForbiddenFinding(
                kind="services",
                reason=(
                    "ст. 779 и 781 ГК РФ — возмездное оказание услуг, а спор "
                    "идёт по договору поставки: основание — ст. 454, 486, 506, "
                    "516 ГК РФ"
                ),
                severity="HIGH",
            )
        )

    preamble = _PREAMBLE_RE.search(text)
    if preamble and _ART_198.search(preamble.group()) and not _ART_194.search(
        preamble.group()
    ):
        findings.append(
            ForbiddenFinding(
                kind="preamble",
                reason=(
                    "вводная формула «Руководствуясь ст. 198 ГПК РФ» "
                    "неполная: решение принимается по ст. 194–199 ГПК РФ "
                    "(при заочном производстве дополнительно ст. 233)"
                ),
                severity="MEDIUM",
            )
        )

    # R20: неустойка и проценты по ст. 395 ГК РФ в одном разделе при
    # присуждении — за один период это двойная ответственность.
    # «Присуждает» отсекает рассуждение о нормах, «не взыска» — отказ
    # в иске по процентам, когда пары не возникает.
    if (
        _PENALTY.search(text)
        and _ART_395.search(text)
        and _AWARD.search(text)
        and not _NO_395.search(text)
    ):
        findings.append(
            ForbiddenFinding(
                kind="penalty_395",
                reason=(
                    "в проекте есть и неустойка, и проценты по ст. 395 ГК РФ: "
                    "за один и тот же период они не взыскиваются "
                    "одновременно — проверить периоды и оставить одно"
                ),
                severity="MEDIUM",
            )
        )

    return findings
